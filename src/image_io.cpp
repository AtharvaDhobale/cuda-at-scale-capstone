// Helper to skip whitespace and Netpbm comments ('#').
void SkipWhitespaceAndComments(std::ifstream& infile) {
  char ch;
  while (infile.get(ch)) {
    if (std::isspace(static_cast<unsigned char>(ch))) {
      continue;
    }
    if (ch == '#') {
      // Discard characters until end of line.
      std::string comment_line;
      std::getline(infile, comment_line);
      continue;
    }
    // Put back the valid non-whitespace character.
    infile.unget();
    break;
  }
}

