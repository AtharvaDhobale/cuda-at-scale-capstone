bool ImageIO::ReadImage(const std::string& filepath, ImageBuffer* image_out) {
  if (image_out == nullptr) {
    std::cerr << "Error: Output image pointer is null." << std::endl;
    return false;
  }

  std::ifstream infile(filepath, std::ios::binary);
  if (!infile.is_open()) {
    std::cerr << "Error: Unable to open file: " << filepath << std::endl;
    return false;
  }

  std::string magic_number;
  infile >> magic_number;

  int channels = 0;
  if (magic_number == "P5") {
    channels = 1;  // Binary grayscale
  } else if (magic_number == "P6") {
    channels = 3;  // Binary RGB
  } else {
    std::cerr << "Error: Unsupported Netpbm format '" << magic_number
              << "' in file: " << filepath
              << ". Only P5 (PGM binary) and P6 (PPM binary) are supported."
              << std::endl;
    return false;
  }

  SkipWhitespaceAndComments(infile);

  int width = 0;
  int height = 0;
  int maxval = 0;

  if (!(infile >> width)) {
    std::cerr << "Error: Failed to read image width from " << filepath << std::endl;
    return false;
  }

  SkipWhitespaceAndComments(infile);

  if (!(infile >> height)) {
    std::cerr << "Error: Failed to read image height from " << filepath << std::endl;
    return false;
  }

  SkipWhitespaceAndComments(infile);

  if (!(infile >> maxval)) {
    std::cerr << "Error: Failed to read max value from " << filepath << std::endl;
    return false;
  }

  if (maxval > 255) {
    std::cerr << "Error: 16-bit images (maxval > 255) not supported: " << filepath << std::endl;
    return false;
  }

  // Consume single whitespace / newline character after maxval before binary data.
  infile.get();

  size_t total_bytes = static_cast<size_t>(width) * height * channels;
  *image_out = ImageBuffer(width, height, channels);

  infile.read(reinterpret_cast<char*>(image_out->data()), total_bytes);
  if (infile.gcount() != static_cast<std::streamsize>(total_bytes)) {
    std::cerr << "Warning: Read " << infile.gcount() << " bytes, expected "
              << total_bytes << " from " << filepath << std::endl;
  }

  return true;
}

bool ImageIO::WriteImage(const std::string& filepath, const ImageBuffer& image) {
  if (image.IsEmpty()) {
    std::cerr << "Error: Cannot write empty image to " << filepath << std::endl;
    return false;
  }

  std::ofstream outfile(filepath, std::ios::binary);
  if (!outfile.is_open()) {
    std::cerr << "Error: Unable to open file for writing: " << filepath << std::endl;
    return false;
  }

  // Write Netpbm header
  if (image.channels() == 1) {
    outfile << "P5\n";
  } else if (image.channels() == 3) {
    outfile << "P6\n";
  } else {
    std::cerr << "Error: Unsupported channel count: " << image.channels() << std::endl;
    return false;
  }

  outfile << "# Generated by CUDA at Scale Enterprise Pipeline\n";
  outfile << image.width() << " " << image.height() << "\n";
  outfile << "255\n";

  outfile.write(reinterpret_cast<const char*>(image.data()), image.TotalBytes());
  return outfile.good();
}

std::vector<std::string> ImageIO::ListImageFiles(const std::string& directory_path) {
  std::vector<std::string> file_list;

#if HAS_STD_FILESYSTEM
  try {
    if (fs::exists(directory_path) && fs::is_directory(directory_path)) {
      for (const auto& entry : fs::directory_iterator(directory_path)) {
        if (entry.is_regular_file()) {
          std::string ext = entry.path().extension().string();
          std::transform(ext.begin(), ext.end(), ext.begin(), ::tolower);
          if (ext == ".pgm" || ext == ".ppm") {
            file_list.push_back(entry.path().string());
          }
        }
      }
    }
  } catch (const std::exception& e) {
    std::cerr << "Filesystem error while scanning " << directory_path << ": " << e.what() << std::endl;
  }
#else
  DIR* dir = opendir(directory_path.c_str());
  if (dir != nullptr) {
    struct dirent* ent;
    while ((ent = readdir(dir)) != nullptr) {
      std::string name(ent->d_name);
      if (name.length() > 4) {
        std::string ext = name.substr(name.length() - 4);
        std::transform(ext.begin(), ext.end(), ext.begin(), ::tolower);
        if (ext == ".pgm" || ext == ".ppm") {
          file_list.push_back(directory_path + "/" + name);
        }
      }
    }
    closedir(dir);
  }
#endif

  std::sort(file_list.begin(), file_list.end());
  return file_list;
}

std::string ImageIO::GetBaseFilename(const std::string& filepath) {
  size_t last_slash = filepath.find_last_of("/\\");
  if (last_slash == std::string::npos) {
    return filepath;
  }
  return filepath.substr(last_slash + 1);
}

std::string ImageIO::FormatOutputFilename(const std::string& input_filepath,
                                          const std::string& filter_name,
                                          const std::string& output_dir) {
  std::string base = GetBaseFilename(input_filepath);
  size_t last_dot = base.find_last_of('.');
  std::string stem = (last_dot == std::string::npos) ? base : base.substr(0, last_dot);
  std::string ext = (last_dot == std::string::npos) ? ".ppm" : base.substr(last_dot);

  return output_dir + "/" + stem + "_" + filter_name + ext;
}

